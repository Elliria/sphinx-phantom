import os
import atexit

# Project metadata
project = 'Sphinx Phantom'
copyright = '2026, Elliria'
author = 'Elliria'

# Minimal Sphinx configuration
extensions = []
templates_path = ['_templates']
exclude_patterns = ['_build', 'Thumbs.db', '.DS_Store']
html_theme = 'alabaster'

# --- THE PHANTOM MECHANISM ---
INDEX_FILE = 'index.rst'

# 1. Synthesize the root document in memory/disk before parsing
index_content = """
Sphinx Phantom
==============

Welcome to a live Sphinx documentation site generated by a repository with **zero static document files**.

How this works:
----------------
- This page was dynamically synthesized inside ``conf.py`` at build time.
- Once ``sphinx-build`` completes HTML compilation, a cleanup hook deletes this file.
- The Git repository contains no Markdown or reST files!
"""

with open(INDEX_FILE, 'w', encoding='utf-8') as f:
    f.write(index_content)

# 2. Register cleanup hook to erase index.rst after compilation
def cleanup():
    if os.path.exists(INDEX_FILE):
        os.remove(INDEX_FILE)

atexit.register(cleanup)
